#!/usr/bin/env node
// Generate CURRENT_STATE.md from the per-stream files in state/*.md and the tasks-axi backlog
// (backlog.md). CURRENT_STATE.md is a DERIVED index - never hand-edit it.
//
// Why: with several agents working in parallel, a single hand-written CURRENT_STATE.md is the
// ADR-0005 one-writer collision applied to docs. Here each stream owns exactly one state/*.md file
// (no shared-file contention), task status lives in tasks-axi (lock-safe), and this script composes
// the human-facing index from both - costing zero model tokens and never drifting.
//
// Run:  node .agents/backlog/gen-current-state.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BACKLOG_DIR = dirname(fileURLToPath(import.meta.url));
const STATE_DIR = join(BACKLOG_DIR, "state");
const BACKLOG = join(BACKLOG_DIR, "backlog.md");
const OUT = join(BACKLOG_DIR, "CURRENT_STATE.md");

// Parse a state file's front-matter (the block between the first two `---` fences).
function frontMatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const i = line.indexOf(":");
    if (i === -1) continue;
    fm[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return fm;
}

// Parse the tasks-axi backlog into id -> section ("In flight" | "Queued" | "Done") and per-section
// id lists, by tracking the current `## <Section>` header and matching `- [ ] <id> - ` task lines.
function parseBacklog() {
  const byId = new Map();
  const sections = {};
  if (!existsSync(BACKLOG)) return { byId, sections };
  let section = null;
  for (const line of readFileSync(BACKLOG, "utf8").split(/\r?\n/)) {
    const h = line.match(/^##\s+(.*\S)/);
    if (h) { section = h[1].trim(); continue; }
    const t = line.match(/^- \[[ xX]\]\s+(\S+)\s+-\s+/);
    if (t && section) {
      byId.set(t[1], section);
      (sections[section] ??= []).push(t[1]);
    }
  }
  return { byId, sections };
}

function readStates() {
  if (!existsSync(STATE_DIR)) return [];
  return readdirSync(STATE_DIR)
    .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
    .map((f) => ({ file: f, ...frontMatter(readFileSync(join(STATE_DIR, f), "utf8")) }))
    .sort((a, b) => (b.updated || "").localeCompare(a.updated || ""));
}

const { byId, sections } = parseBacklog();
const states = readStates();
const today = new Date().toISOString().slice(0, 10);

const rows = states.map((s) => {
  const id = s.task && s.task !== "none" ? s.task : null;
  const taskCell = id ? `\`${id}\`${byId.has(id) ? ` (${byId.get(id)})` : " (not in backlog)"}` : "-";
  return `| ${s.title || s.stream || s.file} | ${s.status || "-"} | ${taskCell} | ${s.updated || "-"} | [state/${s.file}](state/${s.file}) |`;
});

const list = (arr) => (arr && arr.length ? arr.map((i) => `\`${i}\``).join(", ") : "-");
const done = sections["Done"] || [];

const out = `# Current State (generated)

> GENERATED by \`node .agents/backlog/gen-current-state.mjs\` from \`state/*.md\` + \`backlog.md\`.
> Do NOT edit this file by hand. Edit your own \`state/<stream>.md\` (you own exactly one) and re-run the generator.
> Last generated: ${today}

## Streams

| Stream | Status | Task | Updated | Detail |
|--------|--------|------|---------|--------|
${rows.length ? rows.join("\n") : "| (no state/*.md files yet) | - | - | - | - |"}

## Backlog (tasks-axi \`backlog.md\` is the source of truth for task state)

- In flight: ${list(sections["In flight"])}
- Queued: ${list(sections["Queued"])}
- Done: ${done.length}${done.length ? ` (latest: \`${done[0]}\`)` : ""}
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${states.length} stream(s), ${byId.size} backlog task(s)`);
